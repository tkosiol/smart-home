const AI_NAMES = ['claude', 'anthropic'];

/**
 * True if a commit message or PR text carries an AI attribution line (repository convention).
 * Works line by line with plain substring checks so that untrusted PR text cannot trigger
 * regex backtracking (ReDoS).
 */
export function hasAiAttribution(text) {
  return (text ?? '').split('\n').some((rawLine) => {
    const line = rawLine.toLowerCase();
    if (line.includes('🤖 generated')) return true;

    const coAuthor = line.indexOf('co-authored-by:');
    if (coAuthor !== -1 && AI_NAMES.some((name) => line.includes(name, coAuthor))) return true;

    return ['generated with', 'generated by'].some((phrase) => {
      const at = line.indexOf(phrase);
      return at !== -1 && line.includes('claude', at);
    });
  });
}

import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const cli = fileURLToPath(new URL('../commit/check-pr-text.mjs', import.meta.url));

function run(env) {
  return spawnSync(process.execPath, [cli], {
    env: { PATH: process.env.PATH, ...env },
    encoding: 'utf8',
  });
}

describe('check-pr-text CLI', () => {
  it('passes a clean PR', () => {
    expect(
      run({ PR_TITLE: 'feat(backend): add health', PR_BODY: 'Adds the endpoint.' }).status,
    ).toBe(0);
  });

  it('fails when the body carries an AI attribution', () => {
    const result = run({
      PR_TITLE: 'feat(backend): add health',
      PR_BODY: 'Adds it.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)',
    });
    expect(result.status).toBe(1);
    expect(result.stderr).toContain('AI attribution');
  });

  it('fails when the title carries an AI attribution', () => {
    expect(run({ PR_TITLE: 'feat: x generated by Claude', PR_BODY: '' }).status).toBe(1);
  });

  it('treats a missing body as empty', () => {
    expect(run({ PR_TITLE: 'docs: update readme' }).status).toBe(0);
  });
});
